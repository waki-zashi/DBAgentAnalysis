import gzip
import re
import sys
import urllib.request
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent
RAW = ROOT / "data" / "uni_raw"
RAW.mkdir(parents=True, exist_ok=True)

CLEAN_URL = "https://database-sample-website.s3.eu-north-1.amazonaws.com/datasets/university-sample-database/v2/flagship/1k/postgres.sql.gz"
DIRTY_URL = "https://database-sample-website.s3.eu-north-1.amazonaws.com/datasets/university-sample-database/v2/flagship/1k/dirty-postgres.sql.gz"

CREATE_RE = re.compile(r'CREATE TABLE\s+"?(\w+)"?\s*\((.*?)\);', re.IGNORECASE | re.DOTALL)
INSERT_RE = re.compile(r'INSERT INTO\s+"?(\w+)"?\s*\(([^)]*)\)\s*VALUES', re.IGNORECASE)

STRIP_TOKENS = [
    r'\bGENERATED BY DEFAULT AS IDENTITY\b',
    r'\bGENERATED ALWAYS AS IDENTITY\b',
    r'\bPRIMARY KEY\b',
    r'\bUNIQUE\b',
    r'\bNOT NULL\b',
    r'\bDEFAULT\b.*$',
]


def fetch(url, dest):
    if dest.exists():
        print(f"  (уже скачан) {dest.name}")
        return dest.read_bytes()
    print(f"  скачиваю {url} ...")
    with urllib.request.urlopen(url, timeout=60) as r:
        data = r.read()
    dest.write_bytes(data)
    print(f"  -> {dest} ({len(data)} байт)")
    return data


def load_sql(gz_bytes):
    return gzip.decompress(gz_bytes).decode("utf-8", errors="replace")


def parse_create_tables(sql_text):
    tables = {}
    for name, body in CREATE_RE.findall(sql_text):
        cols = []
        depth = 0
        current = ""
        for ch in body:
            if ch == "(":
                depth += 1
            elif ch == ")":
                depth -= 1
            if ch == "," and depth == 0:
                cols.append(current.strip())
                current = ""
            else:
                current += ch
        if current.strip():
            cols.append(current.strip())
        col_defs = []
        for c in cols:
            c = c.strip()
            if re.match(r'^(CONSTRAINT|PRIMARY KEY|FOREIGN KEY|UNIQUE|CHECK)\b', c, re.IGNORECASE):
                continue
            m = re.match(r'^"?(\w+)"?\s+(.+)$', c)
            if not m:
                continue
            col_name, col_type = m.group(1), m.group(2)
            for pat in STRIP_TOKENS:
                col_type = re.sub(pat, '', col_type, flags=re.IGNORECASE)
            col_type = re.sub(r'\bcharacter varying\b', 'VARCHAR', col_type, flags=re.IGNORECASE)
            col_type = re.sub(r'\bdouble precision\b', 'DOUBLE', col_type, flags=re.IGNORECASE)
            col_type = col_type.strip().rstrip(',').strip()
            col_defs.append((col_name, col_type))
        tables[name] = col_defs
    return tables


def parse_values(text, start):
    i, n = start, len(text)
    rows, row, value = [], None, []
    depth, in_string = 0, False

    def push_value():
        row.append("".join(value).strip())
        value.clear()

    while i < n:
        ch = text[i]
        if in_string:
            if ch == "'":
                if i + 1 < n and text[i + 1] == "'":
                    value.append("'")
                    i += 2
                    continue
                in_string = False
                i += 1
                continue
            value.append(ch)
            i += 1
            continue
        if depth == 0:
            if ch == "(":
                depth, row = 1, []
                i += 1
                continue
            if ch == ";":
                return rows, i + 1
            i += 1
            continue
        if ch == "'":
            in_string = True
            i += 1
            continue
        if ch == "(":
            depth += 1
            value.append(ch)
            i += 1
            continue
        if ch == ")":
            depth -= 1
            if depth == 0:
                push_value()
                rows.append(row)
                row = None
            else:
                value.append(ch)
            i += 1
            continue
        if ch == "," and depth == 1:
            push_value()
            i += 1
            continue
        value.append(ch)
        i += 1
    raise ValueError("unterminated VALUES clause")


def sql_literal_to_py(v):
    if v == "NULL":
        return None
    if v in ("true", "false"):
        return v == "true"
    return v


def parse_inserts(sql_text):
    data = {}
    for m in INSERT_RE.finditer(sql_text):
        table = m.group(1)
        cols = [c.strip().strip('"') for c in m.group(2).split(",")]
        rows, _ = parse_values(sql_text, m.end())
        entry = data.setdefault(table, {"columns": cols, "rows": []})
        for r in rows:
            if len(r) != len(cols):
                print(f"  !! {table}: cols={len(cols)} vals={len(r)} -> {r}", file=sys.stderr)
                continue
            entry["rows"].append({c: sql_literal_to_py(v) for c, v in zip(cols, r)})
    return data


def main():
    clean_bytes = fetch(CLEAN_URL, RAW / "clean.sql.gz")
    dirty_bytes = fetch(DIRTY_URL, RAW / "dirty.sql.gz")

    clean_sql = load_sql(clean_bytes)
    dirty_sql = load_sql(dirty_bytes)

    schema = parse_create_tables(clean_sql)
    print(f"\nнайдено таблиц в CREATE TABLE (чистый дамп): {len(schema)}")
    for t, cols in schema.items():
        print(f"  {t:28s} {len(cols)} колонок: {[c for c, _ in cols]}")

    clean_data = parse_inserts(clean_sql)
    dirty_data = parse_inserts(dirty_sql)
    print(f"\nтаблиц с данными: чистая={len(clean_data)} грязная={len(dirty_data)}")

    (RAW / "schema_raw.txt").write_text(
        "\n\n".join(f"-- {t}\n" + "\n".join(f"  {c} {ty}" for c, ty in cols)
                    for t, cols in schema.items()),
        encoding="utf-8",
    )

    diff_lines = []
    total_changed = total_added = total_removed = 0
    for t in sorted(set(clean_data) | set(dirty_data)):
        cd = clean_data.get(t, {"columns": [], "rows": []})
        dd = dirty_data.get(t, {"columns": [], "rows": []})
        if "id" not in cd["columns"]:
            diff_lines.append(f"## {t} -- нет колонки id (строк: чистых {len(cd['rows'])}, грязных {len(dd['rows'])})")
            continue
        clean_by_id = {int(r["id"]): r for r in cd["rows"]}
        dirty_by_id = {int(r["id"]): r for r in dd["rows"]}
        common = set(clean_by_id) & set(dirty_by_id)
        added = set(dirty_by_id) - set(clean_by_id)
        removed = set(clean_by_id) - set(dirty_by_id)

        col_changes = defaultdict(list)
        for pk in common:
            crow, drow = clean_by_id[pk], dirty_by_id[pk]
            for col in cd["columns"]:
                cv, dv = crow.get(col), drow.get(col)
                if cv != dv:
                    col_changes[col].append((pk, cv, dv))

        n_changed_rows = len({pk for vals in col_changes.values() for pk, _, _ in vals})
        if not col_changes and not added and not removed:
            continue
        diff_lines.append(f"## {t}  (строки: чистых {len(cd['rows'])}, грязных {len(dd['rows'])}, "
                           f"изменённых строк {n_changed_rows}, добавлено {len(added)}, удалено {len(removed)})")
        for col, vals in sorted(col_changes.items(), key=lambda kv: -len(kv[1])):
            diff_lines.append(f"  колонка `{col}`: {len(vals)} изменений, примеры:")
            for pk, cv, dv in vals[:5]:
                diff_lines.append(f"    id={pk}: {cv!r} -> {dv!r}")
        if added:
            diff_lines.append(f"  добавленные id (возможные дубликаты): {sorted(added)[:10]}{' ...' if len(added) > 10 else ''}")
        if removed:
            diff_lines.append(f"  удалённые id: {sorted(removed)[:10]}{' ...' if len(removed) > 10 else ''}")
        diff_lines.append("")
        total_changed += n_changed_rows
        total_added += len(added)
        total_removed += len(removed)

    report = RAW / "diff_report.txt"
    report.write_text("\n".join(diff_lines), encoding="utf-8")
    print(f"\nвсего изменённых строк: {total_changed}, добавлено: {total_added}, удалено: {total_removed}")
    print(f"полный отчёт по дифу -> {report}")
    print(f"сырая схема (из CREATE TABLE) -> {RAW / 'schema_raw.txt'}")


if __name__ == "__main__":
    main()
